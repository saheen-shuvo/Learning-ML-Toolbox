# NumPy Introduction
# NumPy is a powerful library for numerical computing in Python. It provides support for large, multi-dimensional arrays and matrices, along with a collection of mathematical functions to operate on these arrays efficiently.

# NumPy means Numerical Python. It is widely used in data analysis, machine learning, and scientific computing.

# Core Structures:
# The core structure of NumPy is the ndarray (n-dimensional array). It is a fast, flexible container for large datasets in Python. The ndarray allows for efficient storage and manipulation of numerical data.

# Ndarray is a homogeneous array, meaning all elements must be of the same data type. It supports various data types, including integers, floats, and complex numbers.
